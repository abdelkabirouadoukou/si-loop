#!/usr/bin/env python3
"""results/study3/make_study3_paper.py: every statistic and figure in paper_study3.tex, from seed_summary.json.

Writes:
  results/study3/numbers.tex        LaTeX macros (\\S3...), \\input by paper_study3.tex
  docs/img/study3_seeds.pdf         per-seed gains, selection and held-out, for the paper

    python results/study3/make_study3_paper.py
Requires scipy (exact and t intervals) and matplotlib (figure).
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy import stats

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DATA = json.loads((HERE / "seed_summary.json").read_text())
OUT_TEX = HERE / "numbers.tex"
OUT_FIG = ROOT / "docs" / "img" / "study3_seeds.pdf"


def t_ci(xs, level=0.95):
    n = len(xs)
    m = sum(xs) / n
    sd = (sum((x - m) ** 2 for x in xs) / (n - 1)) ** 0.5
    half = stats.t.ppf(0.5 + level / 2, n - 1) * sd / n ** 0.5
    return m, sd, m - half, m + half


def exact_ci(k, n, level=0.95):
    """Clopper-Pearson interval for k successes out of n."""
    a = 1 - level
    lo = 0.0 if k == 0 else stats.beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else stats.beta.ppf(1 - a / 2, k + 1, n - k)
    return float(lo), float(hi)


def f3(x):
    return f"{x:.3f}"


def main() -> int:
    runs = DATA["runs"]
    pre = [r for r in runs if r["group"] == "pre-registered"]
    seeded = [r for r in runs if r["group"] in ("early", "pre-registered")]   # seeds 1-9
    assert len(pre) == 6 and len(seeded) == 9

    sel_m, sel_sd, sel_lo, sel_hi = t_ci([r["selection_gain"] for r in pre])
    held_m, held_sd, held_lo, held_hi = t_ci([r["heldout_gain"] for r in pre])
    rep_k = sum(1 for r in pre if r["meets_repeatability"])
    transfer_k = sum(1 for r in pre if r["heldout_gain"] > 0)
    transfer_all_k = sum(1 for r in seeded if r["heldout_gain"] > 0)
    sel_pos_all = sum(1 for r in seeded if r["selection_gain"] > 0)
    gap_pos_all = sum(1 for r in seeded if r["selection_gain"] - r["heldout_gain"] > 0)
    rep_lo, rep_hi = exact_ci(rep_k, 6)
    tr_lo, tr_hi = exact_ci(transfer_k, 6)
    trall_lo, trall_hi = exact_ci(transfer_all_k, 9)

    det = {(r["variant"], r["suite"]): r["rate"]
           for r in json.loads((HERE / "suite_detection.json").read_text())["rows"]}

    macros = {
        "ThrSelMean": f3(sel_m), "ThrSelSD": f3(sel_sd), "ThrSelLo": f3(sel_lo), "ThrSelHi": f3(sel_hi),
        "ThrHeldMean": f3(held_m), "ThrHeldSD": f3(held_sd), "ThrHeldLo": f3(held_lo), "ThrHeldHi": f3(held_hi),
        "ThrRepK": str(rep_k), "ThrRepLo": f3(rep_lo), "ThrRepHi": f3(rep_hi),
        "ThrTransferK": str(transfer_k), "ThrTrLo": f3(tr_lo), "ThrTrHi": f3(tr_hi),
        "ThrTransferAllK": str(transfer_all_k), "ThrTrAllLo": f3(trall_lo), "ThrTrAllHi": f3(trall_hi),
        "ThrSelPosAll": str(sel_pos_all), "ThrGapPosAll": str(gap_pos_all),
        "ThrDetLoopVone": f"{100 * det[('loop_by_second', 'v1')]:.1f}",
        "ThrDetLoopVtwo": f"{100 * det[('loop_by_second', 'v2')]:.1f}",
        "ThrDetMapVone": f"{100 * det[('hash_map_one_pass', 'v1')]:.1f}",
        "ThrDetMapVtwo": f"{100 * det[('hash_map_one_pass', 'v2')]:.1f}",
        "ThrMissLoopVtwo": f"{100 - 100 * det[('loop_by_second', 'v2')]:.1f}",
    }
    lines = ["% Generated by results/study3/make_study3_paper.py from seed_summary.json. Do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    OUT_TEX.write_text("\n".join(lines) + "\n")

    # Tables for the paper, generated so that no number is typed by hand.
    seed_rows = []
    for r in seeded:
        s = r["name"].split()[-1]
        acc = "--" if r.get("correctness_accepts") is None else str(r["correctness_accepts"])
        seed_rows.append(f"{s} & {r['suite']} & {acc} & {f3(r['selection_gain'])} & {f3(r['heldout_gain'])} & "
                         f"{f3(r['selection_gain'] - r['heldout_gain'])} \\\\")
    seed_tab = ("\\begin{tabular}{rlrrrr}\n\\toprule\n"
                "Seed & Suite & Accepts & Sel.\\ gain & Held-out gain & Gap \\\\\n\\midrule\n"
                + "\n".join(seed_rows) + "\n\\bottomrule\n\\end{tabular}\n")
    (HERE / "tab_seeds.tex").write_text(seed_tab)
    det_rows = []
    for variant, label in (("loop_by_second", "loop ordered by second index"),
                           ("hash_map_one_pass", "one-pass hash map")):
        det_rows.append(f"{label} & {100 * det[(variant, 'v1')]:.1f} & {100 * det[(variant, 'v2')]:.1f} \\\\")
    det_tab = ("\\begin{tabular}{lrr}\n\\toprule\n"
               "Buggy variant & v1 (\\%) & v2 (\\%) \\\\\n\\midrule\n"
               + "\n".join(det_rows) + "\n\\bottomrule\n\\end{tabular}\n")
    (HERE / "tab_detection.tex").write_text(det_tab)

    # Figure: one panel per gain, one dot per seed, colour by judge suite.
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9), sharey=True)
    for ax, key, title in ((axes[0], "selection_gain", "Selection families (sealed)"),
                           (axes[1], "heldout_gain", "Held-out parsing family (never selected on)")):
        xs = list(range(1, 10))
        ys = [next(r[key] for r in seeded if r["name"] == f"seed {s}") for s in xs]
        colours = ["#8a8a8a" if s <= 3 else "#1f5fa8" for s in xs]
        ax.bar(xs, ys, color=colours, alpha=0.55, width=0.6)
        ax.scatter(xs, ys, color=colours, s=18, zorder=3)
        ax.axhline(0, color="black", lw=0.6)
        ax.set_title(title, fontsize=9)
        ax.set_xlabel("seed", fontsize=8)
        ax.set_xticks(xs)
        ax.tick_params(labelsize=7)
        ax.set_ylim(-0.02, 0.45)
    axes[0].set_ylabel("gain over anchor (pass rate)", fontsize=8)
    fig.tight_layout()
    OUT_FIG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_FIG)
    print(f"wrote {OUT_TEX} and {OUT_FIG}")
    for k, v in macros.items():
        print(f"  {k} = {v}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
