"""SI-Loop toy prototype: a closed loop of hypernetwork, worker, curriculum engine,
guarded judge and a competitive workspace, on a synthetic few-shot regression task.

Roles
    A  Hyper       support set + workspace broadcast -> low-rank adapter for B
    B  Worker      small MLP, adapted by a few inner SGD steps from A's adapter
    C  DataEngine  learnability-driven curriculum (REINFORCE over difficulty bins)
    D  Judge       sealed RNG, fresh selection tasks, hidden noisy canary,
                   generalisation-gap monitor, rollback
    W  Workspace   "Mom Center": limited-capacity competition for broadcast

Task family: few-shot regression of y = a * sin(w * x + p).

This is a research scaffold, not a benchmark. It makes no claim about scaling
to language models. Weight updates are first-order (no second-order MAML terms).

Usage
    python si_loop_toy.py --arm full --seed 0
    python si_loop_toy.py --ablation --seeds 0 1 2 --out results/ablation.json
"""
from __future__ import annotations

import argparse
import copy
import json
import math
import os
import statistics

import torch
import torch.nn as nn
import torch.nn.functional as F

# Constants
H, R = 32, 4            # worker width, adapter rank
K_SUP, K_QRY = 10, 40   # support / query points per task
INNER, LR_IN = 3, 0.05  # inner adaptation steps and step size
WS_D = 16               # workspace embedding dimension
TAU = 0.3               # query-MSE threshold counted as "success" by the curriculum

ARMS = {
    "full": dict(ws="compete", judge=True),
    "no_ws": dict(ws="off", judge=True),          # broadcast replaced by zeros
    "random_ws": dict(ws="random", judge=True),   # same capacity, random winners
    "no_judge": dict(ws="compete", judge=False),  # every round accepted
}


# Task world

def make_task(difficulty: float, g: torch.Generator) -> torch.Tensor:
    """Sample (amplitude, frequency, phase). Higher difficulty -> higher frequency range."""
    a = 0.5 + 2.0 * torch.rand((), generator=g)
    w = 0.5 + 3.0 * difficulty * torch.rand((), generator=g)
    p = math.pi * torch.rand((), generator=g)
    return torch.stack([a, w, p])


def sample_xy(task: torch.Tensor, n: int, g: torch.Generator):
    x = torch.rand(n, 1, generator=g) * 10 - 5
    return x, task[0] * torch.sin(task[1] * x + task[2])


def task_data(task: torch.Tensor, g: torch.Generator):
    xs, ys = sample_xy(task, K_SUP, g)
    xq, yq = sample_xy(task, K_QRY, g)
    return xs, ys, xq, yq


def make_eval_set(n: int, g: torch.Generator, hard: bool = False):
    d = (0.4 + 0.6 * torch.rand(n, generator=g)) if hard else torch.rand(n, generator=g)
    return [task_data(make_task(x.item(), g), g) for x in d]


# Model B (worker) and Model A (hypernetwork)

class Worker(nn.Module):
    """MLP whose hidden layer accepts a low-rank adapter plus biases generated by A."""

    def __init__(self):
        super().__init__()
        self.f1 = nn.Linear(1, H)
        self.f2 = nn.Linear(H, H)
        self.f3 = nn.Linear(H, 1)

    def forward(self, x, ad):
        h = F.relu(self.f1(x) + ad["b1"])
        h = F.relu(self.f2(h) + (h @ ad["V"]) @ ad["U"].T + ad["b2"])
        return self.f3(h)


ADAPTER_SHAPES = {"U": (H, R), "V": (H, R), "b1": (H,), "b2": (H,)}


class Hyper(nn.Module):
    """Model A: encodes the support set, conditions on the workspace broadcast, emits adapter weights."""

    def __init__(self):
        super().__init__()
        self.enc = nn.Sequential(nn.Linear(2, 32), nn.ReLU(), nn.Linear(32, 32))
        n_out = sum(math.prod(s) for s in ADAPTER_SHAPES.values())
        self.gen = nn.Sequential(nn.Linear(32 + WS_D, 128), nn.ReLU(), nn.Linear(128, n_out))
        with torch.no_grad():  # start near the identity adapter
            self.gen[-1].weight.mul_(0.1)
            self.gen[-1].bias.zero_()

    def forward(self, xs, ys, ws):
        z = self.enc(torch.cat([xs, ys], -1)).mean(0)
        flat = self.gen(torch.cat([z, ws]))
        out, i = {}, 0
        for k, shape in ADAPTER_SHAPES.items():
            n = math.prod(shape)
            out[k] = flat[i:i + n].view(*shape)
            i += n
        return out


def adapt(B: Worker, ad0: dict, xs, ys, steps: int = INNER, lr: float = LR_IN) -> dict:
    """Inner loop: a few SGD steps on the adapter only (B's weights stay fixed)."""
    ad = {k: v.detach().clone().requires_grad_() for k, v in ad0.items()}
    for _ in range(steps):
        loss = F.mse_loss(B(xs, ad), ys)
        grads = torch.autograd.grad(loss, list(ad.values()))
        ad = {k: (v - lr * g).detach().requires_grad_() for (k, v), g in zip(ad.items(), grads)}
    return ad


def meta_step(A, B, tasks, ws, opt_a, opt_b, g):
    """First-order meta-update.

    The query-loss gradient reaches B directly and reaches A by pushing
    dL/d(adapted adapter) through A's initial adapter ad0 = A(support, ws).
    Returns per-task query loss, per-task zero-inner-step loss (quality of A's
    initialisation alone), and pre-clip gradient norms of A and B.
    """
    opt_a.zero_grad()
    opt_b.zero_grad()
    lq_all, lq0_all = [], []
    for t in tasks:
        xs, ys, xq, yq = task_data(t, g)
        ad0 = A(xs, ys, ws)
        ad = adapt(B, ad0, xs, ys)
        lq = F.mse_loss(B(xq, ad), yq)
        (lq / len(tasks)).backward()
        torch.autograd.backward(list(ad0.values()), [ad[k].grad for k in ad0])
        lq_all.append(lq.item())
        with torch.no_grad():
            lq0_all.append(F.mse_loss(B(xq, ad0), yq).item())
    gn_a = nn.utils.clip_grad_norm_(A.parameters(), 1.0).item()
    gn_b = nn.utils.clip_grad_norm_(B.parameters(), 1.0).item()
    opt_a.step()
    opt_b.step()
    return torch.tensor(lq_all), torch.tensor(lq0_all), gn_a, gn_b


def eval_tasks(A, B, data, ws) -> torch.Tensor:
    """Per-task (query MSE, support MSE) after adaptation."""
    rows = []
    for xs, ys, xq, yq in data:
        with torch.no_grad():
            ad0 = A(xs, ys, ws)
        ad = adapt(B, ad0, xs, ys)
        with torch.no_grad():
            rows.append((F.mse_loss(B(xq, ad), yq).item(), F.mse_loss(B(xs, ad), ys).item()))
    return torch.tensor(rows)



# Model C: curriculum / data engine

class DataEngine:
    """Samples tasks from difficulty bins. The bin distribution is trained with REINFORCE
    to favour bins whose success rate is near 50% (a learnability reward)."""

    def __init__(self, n_bins: int = 5):
        self.n_bins = n_bins
        self.logits = torch.zeros(n_bins)
        self.baseline = 0.0

    def propose(self, n: int, g: torch.Generator):
        probs = F.softmax(self.logits, 0)
        bins = torch.multinomial(probs, n, replacement=True, generator=g)
        tasks = [make_task((b.item() + torch.rand((), generator=g).item()) / self.n_bins, g) for b in bins]
        return bins, tasks

    def update(self, bins, success, lr: float = 0.5) -> dict:
        p = F.softmax(self.logits, 0)
        rewards = {}
        for b in range(self.n_bins):
            mask = bins == b
            if mask.any():
                sr = success[mask].float().mean().item()
                rewards[b] = 4 * sr * (1 - sr)  # peaks at 50% success
        if not rewards:
            return rewards
        grad = torch.zeros(self.n_bins)
        for b, r in rewards.items():
            freq = (bins == b).float().mean()
            grad += freq * (r - self.baseline) * (F.one_hot(torch.tensor(b), self.n_bins).float() - p)
        self.baseline = 0.9 * self.baseline + 0.1 * (sum(rewards.values()) / len(rewards))
        self.logits += lr * grad
        return rewards


# Model D: guarded judge

class Judge:
    """A, B and C never touch this object; they only observe accept/reject.

    Controls: sealed RNG, fresh selection tasks every round, conservative
    lower-confidence-bound gate, hidden canary released as one noisy bit with a
    finite query budget, and a generalisation-gap monitor.
    """

    def __init__(self, seed: int = 12345, n_canary: int = 48, budget: int = 200, sigma: float = 0.02):
        self.g = torch.Generator().manual_seed(seed)          # sealed selection/canary RNG
        self.gd = torch.Generator().manual_seed(seed + 1)     # diagnostics RNG (Shapley set)
        self.canary = make_eval_set(n_canary, self.g, hard=True)
        self.budget, self.sigma, self.gap_ema = budget, sigma, None

    def diag_set(self, n: int = 32):
        return make_eval_set(n, self.gd)

    def judge(self, cand, last, ws_cand, ws_last):
        sel = make_eval_set(32, self.g)                        # fresh tasks: no adaptive overfitting
        new, old = eval_tasks(*cand, sel, ws_cand), eval_tasks(*last, sel, ws_last)
        d = old[:, 0] - new[:, 0]                              # paired per-task improvement
        lcb = d.mean().item() - d.std().item() / math.sqrt(len(d))
        gap = (new[:, 0] - new[:, 1]).mean().item()            # query-minus-support loss
        gap_bad = self.gap_ema is not None and gap > self.gap_ema + 0.25 * abs(self.gap_ema) + 0.02

        self.budget -= 1
        if self.budget < 0:
            raise RuntimeError("canary query budget exhausted: rotate the canary set")
        c_new = eval_tasks(*cand, self.canary, ws_cand)[:, 0].mean().item()
        c_old = eval_tasks(*last, self.canary, ws_last)[:, 0].mean().item()
        noise = torch.distributions.Laplace(0.0, self.sigma).sample().item()
        canary_bad = (c_new - c_old) > 0.05 * c_old + noise    # one noisy bit leaves the vault

        ok = lcb > 0 and not gap_bad and not canary_bad
        if ok:
            self.gap_ema = gap if self.gap_ema is None else 0.8 * self.gap_ema + 0.2 * gap
        return ok, dict(lcb=lcb, gap=gap, gap_bad=gap_bad, canary_bad=canary_bad)


# Mom Center: competition for broadcast

class Workspace:
    """Limited-capacity workspace.

    Candidates compete on a salience score; at most K survive and only those
    above the ignition threshold are broadcast. Entries expire after `ttl`
    rounds, payloads must be numeric (typed), and each source has a post limit.
    mode="random" keeps capacity and TTL but picks winners at random (control).
    """

    def __init__(self, K=4, theta=0.1, ttl=4, rate=2, mode="compete"):
        self.K, self.theta, self.ttl, self.rate, self.mode = K, theta, ttl, rate, mode
        self.slots, self.cands, self.trust, self.t = [], [], {}, 0

    def post(self, src, vec, payload, verified=False) -> bool:
        if not all(isinstance(v, (int, float)) for v in payload.values()):
            return False                                        # typed payloads only
        if sum(c["src"] == src for c in self.cands) >= self.rate:
            return False                                        # per-source rate limit
        self.cands.append(dict(src=src, vec=F.normalize(vec, dim=0), payload=payload,
                               born=self.t, verified=verified))
        return True

    def step(self, query, util):
        self.t += 1
        self.slots = [c for c in self.slots if self.t - c["born"] <= self.ttl]   # staleness bound
        pool, self.cands = self.slots + self.cands, []
        if not pool:
            self.slots = []
            return
        if self.mode == "random":
            idx = torch.randperm(len(pool))[: self.K].tolist()
            self.slots = [pool[i] for i in idx]
            return
        q = F.normalize(query, dim=0)
        scored = []
        for c in pool:
            rel = float(c["vec"] @ q)
            nov = 1 - max([float(c["vec"] @ o["vec"]) for o in pool if o is not c] or [0.0])
            age = (self.t - c["born"]) / self.ttl
            trust = self.trust.get(c["src"], 0.5) * (1.0 if c["verified"] else 0.5)
            sal = 0.5 * rel + 0.3 * nov + 0.3 * trust + 0.2 * util.get(c["src"], 0.0) - 0.3 * age
            scored.append((sal, c))
        scored.sort(key=lambda z: -z[0])
        self.slots = [c for sal, c in scored[: self.K] if sal > self.theta]       # capacity + ignition

    def broadcast(self) -> torch.Tensor:
        if not self.slots:
            return torch.zeros(WS_D)
        return torch.stack([c["vec"] for c in self.slots]).mean(0)

    def credit(self, src, delta):
        self.trust[src] = 0.9 * self.trust.get(src, 0.5) + 0.1 * float(delta > 0)


# Credit assignment: two-player Shapley over model versions (A and B)

def shapley_AB(old, new, data, ws) -> dict:
    """Swap A and B versions on a fixed diagnostic set. phi_A + phi_B equals the total
    improvement exactly; a large interaction term means A and B co-adapted."""
    def v(a, b):
        return -eval_tasks(a, b, data, ws)[:, 0].mean().item()

    v0, v_a, v_b, v_ab = v(old[0], old[1]), v(new[0], old[1]), v(old[0], new[1]), v(new[0], new[1])
    return dict(
        phi_A=0.5 * ((v_a - v0) + (v_ab - v_b)),
        phi_B=0.5 * ((v_b - v0) + (v_ab - v_a)),
        total=v_ab - v0,
        interaction=v_ab - v_a - v_b + v0,
    )


# Closed loop

def run(arm="full", seed=0, rounds=12, steps=40, meta_bs=8, verbose=True) -> dict:
    cfg = ARMS[arm]
    torch.manual_seed(seed)
    g = torch.Generator().manual_seed(seed + 1)
    A, B, C = Hyper(), Worker(), DataEngine()
    D = Judge(seed=10_000 + seed)
    W = Workspace(mode="random" if cfg["ws"] == "random" else "compete")
    use_ws = cfg["ws"] != "off"
    # fixed random projection: scalar training statistics -> workspace embedding
    proj = torch.randn(5, WS_D, generator=torch.Generator().manual_seed(seed + 2))

    def make_opts():
        return torch.optim.Adam(A.parameters(), 1e-3), torch.optim.Adam(B.parameters(), 1e-3)

    def snapshot():
        return copy.deepcopy(A.state_dict()), copy.deepcopy(B.state_dict()), C.logits.clone()

    opt_a, opt_b = make_opts()
    last_state = snapshot()
    last_models = (copy.deepcopy(A), copy.deepcopy(B))
    # last_ws: workspace state the last accepted models were trained/evaluated under
    # ws_next: broadcast computed when the last accepted round finished; the next round trains under it
    ws_vec = last_ws = ws_next = torch.zeros(WS_D)
    util, diag = {}, D.diag_set(32)
    history, n_ok = [], 0

    for r in range(rounds):
        stats = []
        for _ in range(steps):
            bins, tasks = C.propose(meta_bs, g)
            lq, lq0, gn_a, gn_b = meta_step(A, B, tasks, ws_vec, opt_a, opt_b, g)
            rewards = C.update(bins, lq < TAU)
            learn = sum(rewards.values()) / max(len(rewards), 1)
            stats.append([lq.mean().item(), lq0.mean().item(), gn_a, gn_b, learn])
        m = torch.tensor(stats).mean(0).tolist()
        share = F.softmax(C.logits, 0)

        emb_b = torch.tanh(torch.tensor([m[0], m[1], m[2], m[3], 0.0]) @ proj)
        emb_c = torch.tanh(torch.tensor([share[0].item(), share[-1].item(), m[4], m[0], 1.0]) @ proj)
        W.post("B", emb_b, dict(loss=m[0], init_loss=m[1]))
        W.post("C", emb_c, dict(hard_share=share[-1].item(), learnability=m[4]))
        W.post("B", emb_b + 0.01, dict(loss=m[0], init_loss=m[1]))   # near-duplicate: exercises novelty term
        W.step(emb_b, util)
        cand_ws = W.broadcast() if use_ws else torch.zeros(WS_D)

        ws_train = ws_vec                                   # workspace state the candidate trained under
        ok, info = D.judge((A, B), last_models, ws_train, last_ws)
        if not cfg["judge"]:
            ok = True
        row = dict(round=r, train_q=m[0], init_q=m[1], accept=bool(ok),
                   hard_share=share[-1].item(), slots=len(W.slots), **info)
        note = ""
        if ok:
            n_ok += 1
            phi = shapley_AB(last_models, (A, B), diag, ws_train)
            row.update({f"shapley_{k}": v for k, v in phi.items()})
            note = f" | phi_A={phi['phi_A']:+.3f} phi_B={phi['phi_B']:+.3f} inter={phi['interaction']:+.3f}"
            for c in W.slots:
                W.credit(c["src"], info["lcb"])
                util[c["src"]] = 0.8 * util.get(c["src"], 0.0) + 0.2 * info["lcb"]
            last_state, last_models, last_ws = snapshot(), (copy.deepcopy(A), copy.deepcopy(B)), ws_train
            ws_next = ws_vec = cand_ws
        else:
            A.load_state_dict(last_state[0])
            B.load_state_dict(last_state[1])
            C.logits = last_state[2].clone()
            opt_a, opt_b = make_opts()
            ws_vec = ws_next  # a rejected round's broadcast is discarded; retry under the last accepted one
        history.append(row)
        if verbose:
            print(f"[{arm} s{seed}] r{r:02d} train_q={m[0]:.3f} init_q={m[1]:.3f} lcb={info['lcb']:+.3f} "
                  f"gap_bad={info['gap_bad']} canary_bad={info['canary_bad']} accept={ok} "
                  f"slots={len(W.slots)} hard={share[-1].item():.2f}{note}")

    # harness-side final evaluation on sets never used for any decision
    gf = torch.Generator().manual_seed(90_000 + seed)
    final_all = eval_tasks(*last_models, make_eval_set(64, gf), last_ws)[:, 0].mean().item()
    final_hard = eval_tasks(*last_models, make_eval_set(64, gf, hard=True), last_ws)[:, 0].mean().item()
    return dict(arm=arm, seed=seed, final_all=final_all, final_hard=final_hard,
                accept_rate=n_ok / rounds, history=history)


def ablation(seeds, rounds, steps, meta_bs, out):
    results = {arm: [run(arm, s, rounds, steps, meta_bs, verbose=False) for s in seeds] for arm in ARMS}

    def ms(xs):
        return f"{statistics.mean(xs):.3f} ± {statistics.stdev(xs) if len(xs) > 1 else 0.0:.3f}"

    print(f"\n{'arm':<10} {'final_all (MSE)':<18} {'final_hard (MSE)':<18} accept_rate")
    for arm, rs in results.items():
        print(f"{arm:<10} {ms([r['final_all'] for r in rs]):<18} "
              f"{ms([r['final_hard'] for r in rs]):<18} {statistics.mean(r['accept_rate'] for r in rs):.2f}")
    if out:
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        with open(out, "w") as f:
            json.dump(results, f, indent=2)
        print(f"\nsaved {out}")
    return results


def main():
    p = argparse.ArgumentParser(description="SI-Loop toy prototype")
    p.add_argument("--arm", choices=list(ARMS), default="full")
    p.add_argument("--ablation", action="store_true", help="run all arms over --seeds")
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--rounds", type=int, default=12)
    p.add_argument("--steps", type=int, default=40, help="meta-steps per round")
    p.add_argument("--meta-bs", type=int, default=8)
    p.add_argument("--out", default="results/ablation.json")
    a = p.parse_args()
    if a.ablation:
        ablation(a.seeds, a.rounds, a.steps, a.meta_bs, a.out)
    else:
        r = run(a.arm, a.seed, a.rounds, a.steps, a.meta_bs)
        print(f"\nfinal_all={r['final_all']:.3f} final_hard={r['final_hard']:.3f} accept_rate={r['accept_rate']:.2f}")


if __name__ == "__main__":
    main()
